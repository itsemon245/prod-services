#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<'USAGE'
Generate Redis configs, ACL files, the optional HAProxy gateway config and the
generated Compose env from templates.

Usage:
  scripts/generate-redis-config.sh [--env-file PATH] [--output-dir PATH] [--yes]

Defaults:
  --env-file   redis/.env
  --output-dir redis/redis_config

Output, per enabled role (cache, session, queue, ws):
  <output-dir>/<role>/redis.conf          role config (no secrets)
  <output-dir>/<role>/users.acl           ACL users with SHA-256 password hashes
  <output-dir>/<role>/healthcheck.secret  password of the ping-only healthcheck user (0600)
Plus:
  <output-dir>/gateway/haproxy.cfg        when REDIS_GATEWAY=on
  <output-dir>/gateway/allowlist.lst      validated copy of REDIS_GATEWAY_ALLOWLIST_FILE
  <output-dir>/compose.env                project name, profiles and memory limits

Required in redis/.env (generated by ensure-env when empty):
  REDIS_<ROLE>_PASSWORD for each role in REDIS_ROLES
  REDIS_ADMIN_PASSWORD
  REDIS_EXPORTER_PASSWORD when REDIS_EXPORTER=on

Useful tuning overrides:
  REDIS_ROLES, REDIS_<ROLE>_PERSISTENCE, REDIS_<ROLE>_MAXMEMORY_POLICY,
  REDIS_MEMORY_MB, REDIS_CPU_CORES, REDIS_HOST_MEMORY_RESERVE_PERCENT,
  REDIS_MEMORY_BUDGET_PERCENT, REDIS_<ROLE>_MAXMEMORY_MB, REDIS_<ROLE>_MEM_LIMIT_MB
USAGE
}

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_dir="$(cd -- "$script_dir/.." && pwd)"
# shellcheck source=shared/common.sh
source "$script_dir/shared/common.sh"
# shellcheck source=shared/redis.sh
source "$script_dir/shared/redis.sh"

redis_dir="$repo_dir/redis"
template_dir="${REDIS_TEMPLATE_DIR:-$redis_dir/templates}"
output_dir="${REDIS_CONFIG_DIR:-$redis_dir/redis_config}"
env_file="$redis_dir/.env"
ensure_args=()

while [[ $# -gt 0 ]]; do
  case "$1" in
    --env-file)
      [[ $# -ge 2 ]] || die "--env-file requires a path"
      env_file="$2"
      shift 2
      ;;
    --output-dir)
      [[ $# -ge 2 ]] || die "--output-dir requires a path"
      output_dir="$2"
      shift 2
      ;;
    --yes)
      ensure_args+=(--yes)
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      die "unknown argument: $1"
      ;;
  esac
done

"$script_dir/redis-env-check.sh" ensure-env --env-file "$env_file" "${ensure_args[@]}"
"$script_dir/redis-env-check.sh" validate --env-file "$env_file" >/dev/null

load_env_file "$env_file" --preserve-existing

sha256_hex() {
  # printf is a builtin, so the secret never appears in a process argv.
  printf '%s' "$1" | sha256sum | awk '{print $1}'
}

# Writes content to path atomically with the given mode.
write_file() {
  local path="$1" mode="$2" content="$3" tmp

  tmp="$(mktemp "${path}.tmp.XXXXXX")"
  chmod "$mode" "$tmp"
  printf '%s\n' "$content" > "$tmp"
  mv "$tmp" "$path"
}

render() {
  local template="$1" content key
  shift

  [[ -f "$template" ]] || die "missing template: $template"
  content="$(< "$template")"
  while [[ $# -ge 2 ]]; do
    key="$1"
    content="${content//\{\{$key\}\}/$2}"
    shift 2
  done
  [[ "$content" != *"{{"*"}}"* ]] || die "unrendered placeholder left in $template"
  printf '%s\n' "$content"
}

mem_limit_mb() {
  local maxmemory_mb="$1" overhead_percent="$2" minimum_overhead_mb="$3" overhead_mb

  overhead_mb="$(( maxmemory_mb * overhead_percent / 100 ))"
  overhead_mb="$(clamp_min "$overhead_mb" "$minimum_overhead_mb")"
  round_to_step "$(( maxmemory_mb + overhead_mb ))" 16
}

password_hashes() {
  local name="$1" hashes

  hashes="#$(sha256_hex "${!name}")"
  local next="${name}_NEXT"
  if [[ -n "${!next:-}" ]]; then
    hashes+=" #$(sha256_hex "${!next}")"
  fi
  printf '%s\n' "$hashes"
}

persistence_block() {
  case "$1" in
    none)
      printf '%s\n' \
        'appendonly no' \
        'save ""'
      ;;
    rdb)
      # Best-effort snapshots: availability wins over durability, so a failed
      # snapshot does not stop writes. Watch rdb_last_bgsave_status.
      printf '%s\n' \
        'appendonly no' \
        'save 900 1 300 100 60 10000' \
        'stop-writes-on-bgsave-error no' \
        'rdbcompression yes' \
        'rdbchecksum yes' \
        'dbfilename dump.rdb'
      ;;
    aof)
      printf '%s\n' \
        'appendonly yes' \
        'appendfsync everysec' \
        'auto-aof-rewrite-percentage 100' \
        'auto-aof-rewrite-min-size 32mb' \
        'aof-use-rdb-preamble yes' \
        'aof-load-truncated yes' \
        'no-appendfsync-on-rewrite yes' \
        'save 60 1' \
        'save 300 10' \
        'stop-writes-on-bgsave-error yes' \
        'rdbcompression yes' \
        'rdbchecksum yes' \
        'dbfilename dump.rdb'
      ;;
    *) die "unknown persistence mode: $1" ;;
  esac
}

lazyfree_block() {
  case "$1" in
    noeviction) printf 'lazyfree-lazy-user-del yes\n' ;;
    *) printf '%s\n' 'lazyfree-lazy-eviction yes' 'lazyfree-lazy-expire yes' 'lazyfree-lazy-user-del yes' ;;
  esac
}

ensure_healthcheck_secret() {
  local path="$1"

  # Stable across regenerations: the running server only learns a new hash on
  # ACL LOAD or restart, so rotating this on every run would fail healthchecks.
  if [[ ! -s "$path" ]]; then
    write_file "$path" 0600 "$(generate_secret)"
  fi
  chmod 0600 "$path"
  tr -d '\n' < "$path"
}

mapfile -t enabled_roles < <(redis_enabled_roles)
(( ${#enabled_roles[@]} > 0 )) || die "REDIS_ROLES selects no roles"

memory_mb="$(detect_memory_mb REDIS_MEMORY_MB)"
cpu_cores="$(detect_cpu_cores REDIS_CPU_CORES)"
require_positive_uint detected_memory_mb "$memory_mb"
require_positive_uint detected_cpu_cores "$cpu_cores"

host_memory_reserve_percent="$(setting_positive_uint REDIS_HOST_MEMORY_RESERVE_PERCENT 10)"
(( host_memory_reserve_percent < 100 )) || die "REDIS_HOST_MEMORY_RESERVE_PERCENT must be less than 100"
host_memory_reserved_mb="$(( memory_mb * host_memory_reserve_percent / 100 ))"
redis_tuning_memory_mb="$(( memory_mb - host_memory_reserved_mb ))"
(( redis_tuning_memory_mb > 0 )) || die "Redis tuning memory must be greater than zero"

redis_memory_budget_percent="$(setting_positive_uint REDIS_MEMORY_BUDGET_PERCENT 70)"
(( redis_memory_budget_percent <= 100 )) || die "REDIS_MEMORY_BUDGET_PERCENT must be 100 or less"
redis_memory_budget_mb="$(( redis_tuning_memory_mb * redis_memory_budget_percent / 100 ))"
redis_memory_budget_mb="$(clamp_min "$redis_memory_budget_mb" 256)"

# Split the budget across enabled roles only, by their relative weights.
weight_total=0
for role in "${enabled_roles[@]}"; do
  weight_total=$(( weight_total + $(redis_role_default "$role" weight) ))
done

container_overhead_percent="$(setting_positive_uint REDIS_CONTAINER_MEMORY_OVERHEAD_PERCENT 30)"
persistent_overhead_percent="$(setting_positive_uint REDIS_PERSISTENT_CONTAINER_MEMORY_OVERHEAD_PERCENT \
  "$(setting_positive_uint REDIS_QUEUE_CONTAINER_MEMORY_OVERHEAD_PERCENT 50)")"

generated_at="$(date -u +"%Y-%m-%dT%H:%M:%SZ")"
mkdir -p "$output_dir"
chmod 0755 "$output_dir"

app_acl_rules="${REDIS_APP_ACL_RULES:-$REDIS_DEFAULT_APP_ACL_RULES}"
admin_hashes="$(password_hashes REDIS_ADMIN_PASSWORD)"
exporter_acl=""
if redis_exporter_enabled; then
  # Read-only metrics user for redis_exporter.
  exporter_acl="user exporter on $(password_hashes REDIS_EXPORTER_PASSWORD) -@all +@connection +info +ping +dbsize +config|get +client|list +client|info +slowlog|get +slowlog|len +latency|latest +latency|histogram +memory|stats +memory|usage +cluster|info +module|list +select +type +scan"
fi

declare -A mem_limits=()
summary_maxmemory=()
summary_limits=()

for role in "${enabled_roles[@]}"; do
  prefix="$(redis_role_prefix "$role")"
  role_dir="$output_dir/$role"
  mkdir -p "$role_dir"
  chmod 0755 "$role_dir"

  default_mb="$(round_to_step "$(( redis_memory_budget_mb * $(redis_role_default "$role" weight) / weight_total ))" 16)"
  default_mb="$(clamp_min "$default_mb" "$(redis_role_default "$role" min_maxmemory)")"
  maxmemory_mb="$(setting_positive_uint "REDIS_${prefix}_MAXMEMORY_MB" "$default_mb")"

  persistence="$(redis_role_persistence "$role")"
  policy="$(redis_role_policy "$role")"
  if [[ "$persistence" == none ]]; then
    overhead="$container_overhead_percent"
  else
    # Forked BGSAVE/AOF rewrite children need copy-on-write headroom.
    overhead="$persistent_overhead_percent"
  fi
  mem_limit="$(setting_positive_uint "REDIS_${prefix}_MEM_LIMIT_MB" "$(mem_limit_mb "$maxmemory_mb" "$overhead" 64)")"
  mem_limits[$role]="$mem_limit"
  summary_maxmemory+=("$role=${maxmemory_mb}mb")
  summary_limits+=("$role=${mem_limit}m")

  hc_password="$(ensure_healthcheck_secret "$role_dir/healthcheck.secret")"

  acl_content="# Generated by scripts/generate-redis-config.sh on $generated_at
# Role: $(redis_role_default "$role" label). Passwords are SHA-256 hashes; edit redis/.env, not this file.
# default     application user (clients that send only a password)
# ops         operator user for backups, ACL LOAD, migrations
# healthcheck container healthcheck, PING only
user default on $(password_hashes "REDIS_${prefix}_PASSWORD") $app_acl_rules
user ops on $admin_hashes ~* &* +@all
user healthcheck on #$(sha256_hex "$hc_password") -@all +ping"
  if [[ -n "$exporter_acl" ]]; then
    acl_content+=$'\n'"$exporter_acl"
  fi
  # Readable by the redis user in the container; contains hashes only.
  write_file "$role_dir/users.acl" 0644 "$acl_content"

  conf="$(render "$template_dir/redis.conf.tpl" \
    GENERATED_AT "$generated_at" \
    ROLE "$(redis_role_default "$role" label)" \
    HOST_MEMORY_MB "$memory_mb" \
    CPU_CORES "$cpu_cores" \
    HOST_MEMORY_RESERVE_PERCENT "$host_memory_reserve_percent" \
    HOST_MEMORY_RESERVED_MB "$host_memory_reserved_mb" \
    REDIS_MEMORY_BUDGET_PERCENT "$redis_memory_budget_percent" \
    REDIS_MEMORY_BUDGET_MB "$redis_memory_budget_mb" \
    ENABLED_ROLES "${enabled_roles[*]}" \
    PERSISTENCE "$persistence" \
    MAXMEMORY_MB "$maxmemory_mb" \
    MAXMEMORY_POLICY "$policy" \
    MAXMEMORY_SAMPLES "$(redis_role_default "$role" samples)" \
    PERSISTENCE_BLOCK "$(persistence_block "$persistence")" \
    LAZYFREE_BLOCK "$(lazyfree_block "$policy")")"
  write_file "$role_dir/redis.conf" 0644 "$conf"
done

# Legacy single-file outputs from before roles had their own directory. They
# held plaintext requirepass values; replace them with a pointer.
for role in "${REDIS_ALL_ROLES[@]}"; do
  legacy="$output_dir/$role.conf"
  if [[ -f "$legacy" ]] && grep -q '^requirepass ' "$legacy"; then
    write_file "$legacy" 0644 "# Superseded: configs now live in $output_dir/$role/. Safe to delete."
    printf 'Replaced legacy plaintext config %s with a pointer\n' "$legacy"
  fi
done

profiles=("${enabled_roles[@]}")
if redis_exporter_enabled; then
  for role in "${enabled_roles[@]}"; do
    profiles+=("$role-exporter")
  done
fi

if redis_gateway_enabled; then
  profiles+=(gateway)
  gateway_dir="$output_dir/gateway"
  mkdir -p "$gateway_dir"
  chmod 0755 "$gateway_dir"

  allowlist_source="$(resolve_path_relative_to "$redis_dir" "${REDIS_GATEWAY_ALLOWLIST_FILE:-./gateway.allowlist}")"
  allowlist="$("$script_dir/redis-env-check.sh" print-allowlist --env-file "$env_file")"
  allowlist_count="$(printf '%s' "$allowlist" | grep -c . || true)"
  allowlist_content="# Generated from $allowlist_source on $generated_at. Edit the source file, then make reload-redis-gateway.
$allowlist"

  frontends=""
  for role in "${enabled_roles[@]}"; do
    internal_port="$(( 16379 + $(redis_role_default "$role" host_port) - 6379 ))"
    frontends+="
frontend fe_redis_${role}
    bind :${internal_port}
    tcp-request connection reject unless { src -f /usr/local/etc/haproxy/allowlist.lst }
    default_backend be_redis_${role}

backend be_redis_${role}
    server ${role} $(redis_role_service "$role"):6379 resolvers docker init-addr last,libc,none check inter 5s fall 3 rise 2
"
  done

  haproxy_cfg="$(render "$template_dir/haproxy.cfg.tpl" \
    GENERATED_AT "$generated_at" \
    MAXCONN "$(setting_positive_uint REDIS_GATEWAY_MAXCONN 4096)" \
    HARD_STOP_AFTER "${REDIS_GATEWAY_HARD_STOP_AFTER:-1h}" \
    FRONTENDS "$frontends")"

  # Check the new config in a throwaway container before it replaces the live
  # files, so a bad edit can never reach a running or restarting gateway.
  staging_dir="$(mktemp -d "$output_dir/.gateway-staging.XXXXXX")"
  chmod 0755 "$staging_dir"
  write_file "$staging_dir/haproxy.cfg" 0644 "$haproxy_cfg"
  write_file "$staging_dir/allowlist.lst" 0644 "$allowlist_content"
  if [[ "${REDIS_SKIP_GATEWAY_CHECK:-0}" != 1 ]]; then
    if ! check_output="$(docker run --rm --network none \
        -v "$staging_dir:/usr/local/etc/haproxy:ro" \
        "${REDIS_GATEWAY_IMAGE:-$REDIS_DEFAULT_GATEWAY_IMAGE}" \
        haproxy -c -f /usr/local/etc/haproxy/haproxy.cfg 2>&1)"; then
      printf '%s\n' "$check_output" >&2
      die "generated gateway config failed haproxy -c; live config left unchanged (staging: $staging_dir)"
    fi
  fi
  mv "$staging_dir/allowlist.lst" "$gateway_dir/allowlist.lst"
  mv "$staging_dir/haproxy.cfg" "$gateway_dir/haproxy.cfg"
  rmdir "$staging_dir"
fi

override_content="# Generated by scripts/generate-redis-config.sh on $generated_at
# Gateway listener ports for enabled roles only."
if redis_gateway_enabled; then
  override_content+=$'\nservices:\n  redis-gateway:\n    ports:'
  gateway_bind="${REDIS_GATEWAY_BIND_ADDRESS:-0.0.0.0}"
  [[ "$gateway_bind" == *:* ]] && gateway_bind="[$gateway_bind]"
  for role in "${enabled_roles[@]}"; do
    prefix="$(redis_role_prefix "$role")"
    port_name="REDIS_GATEWAY_${prefix}_PORT"
    internal_port="$(( 16379 + $(redis_role_default "$role" host_port) - 6379 ))"
    override_content+=$'\n'"      - \"${gateway_bind}:${!port_name:-$(redis_role_default "$role" gateway_port)}:${internal_port}\""
  done
else
  override_content+=$'\nservices: {}'
fi
write_file "$output_dir/compose.override.yml" 0644 "$override_content"

compose_env="$output_dir/compose.env"
compose_content="# Generated by scripts/generate-redis-config.sh on $generated_at
COMPOSE_PROJECT_NAME=${REDIS_COMPOSE_PROJECT_NAME:-redis}
COMPOSE_PROFILES=$(IFS=,; printf '%s' "${profiles[*]}")
REDIS_CONFIG_DIR=$(cd -- "$output_dir" && pwd -P)"
for role in "${REDIS_ALL_ROLES[@]}"; do
  prefix="$(redis_role_prefix "$role")"
  if [[ -n "${mem_limits[$role]:-}" ]]; then
    compose_content+=$'\n'"REDIS_${prefix}_MEM_LIMIT=${mem_limits[$role]}m"
  else
    # Compose interpolates every service, even ones whose profile is off.
    compose_content+=$'\n'"# $role role disabled; placeholder only, the service is not started."
    compose_content+=$'\n'"REDIS_${prefix}_MEM_LIMIT=64m"
  fi
done
write_file "$compose_env" 0644 "$compose_content"

printf 'Generated Redis configs in %s\n' "$output_dir"
printf 'Enabled roles: %s\n' "${enabled_roles[*]}"
printf 'Compose profiles: %s\n' "$(IFS=,; printf '%s' "${profiles[*]}")"
printf 'Detected resources: %sMB RAM, %s CPU cores\n' "$memory_mb" "$cpu_cores"
printf 'Reserved for host/Docker: %s%% (%sMB); Redis budget: %s%% of %sMB = %sMB\n' \
  "$host_memory_reserve_percent" "$host_memory_reserved_mb" "$redis_memory_budget_percent" "$redis_tuning_memory_mb" "$redis_memory_budget_mb"
printf 'Maxmemory: %s\n' "${summary_maxmemory[*]}"
printf 'Container limits: %s\n' "${summary_limits[*]}"
if redis_gateway_enabled; then
  printf 'Gateway: %s allowlist entries from %s\n' "$allowlist_count" "$allowlist_source"
  (( allowlist_count > 0 )) || printf 'warning: gateway allowlist is empty; every remote connection will be rejected\n' >&2
fi
